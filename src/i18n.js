import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';
import LanguageDetector from 'i18next-browser-languagedetector';
import enTranslation from './locales/en/translation.json';
import arTranslation from './locales/ar/atranslation.json';
import kuTranslation from './locales/ku/translation.json';

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources: {
      en: { translation: enTranslation },
      ar: { translation: arTranslation },
      ku: { translation: kuTranslation },
    },
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
    detection: {
      order: ['localStorage', 'navigator', 'cookie'], // Prioritize localStorage
      caches: ['localStorage'], // Store language in localStorage
      lookupLocalStorage: 'language', // Use 'language' as the key in localStorage
    },
  });

export default i18n;